package mehmethoca.day12_loops;

public class C01_loops1 {
    public static void main(String[] args) {
        //Example 3 : 40 dan 23 e kadar tum cift sayilari ekrana yazdiriniz
        for(int i =40; i>22; i--){
            if(i%2==0){
                System.out.println(i);
            }
        }
    }
}
